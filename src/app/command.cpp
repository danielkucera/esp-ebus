command_types::WriteType parseWriteType(std::string_view name) {
  if (name == "simple") return command_types::WriteType::simple;
  if (name == "weishaupt") return command_types::WriteType::weishaupt;
  return command_types::WriteType::invalid;
}

// Weishaupt's inner checksum shifts incoming bits into the low bit.
// It is separate from the eBUS frame checksum generated by the library.
uint8_t weishauptChecksum(ebus::ByteView payload) {
  uint8_t checksum = 0;
  for (uint8_t byte : payload) {
    for (unsigned bit = 0; bit < 8; ++bit) {
      const uint8_t polynomial = (checksum & 0x80) ? 0x5c : 0;
      checksum = static_cast<uint8_t>((checksum << 1) | (byte >> 7));
      checksum ^= polynomial;
      byte = static_cast<uint8_t>(byte << 1);
    }
  }
  return checksum;
}
